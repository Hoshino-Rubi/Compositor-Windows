"""Port upstream PatchMatch scheduling to C++/MSVC; preserve float workspace precision.
The 16-bit variant maps native samples to the same continuous 0..255 workspace,
not an 8-bit intermediate. Generated outputs are checked in.
"""
from pathlib import Path
import re,hashlib
root=Path(__file__).resolve().parents[2]
original=(root/'Compositor/Rendering/PatchPixels.c').read_text(encoding='utf-8')
for wide in (False,True):
 code=re.sub(r'^#include[^\n]*\n','',original,flags=re.M)
 code=code.replace('static void in_row_bands(int rows, void (^body)(int band, int start, int end))','template<class Body> static void in_row_bands(int rows, Body body)')
 code=code.replace('dispatch_apply((size_t)bands, DISPATCH_APPLY_AUTO,','pixel_parallel((size_t)bands,').replace('^(','[&](')
 code=code.replace('[&](int band, int start, int end) {', '[&](int band, int start, int end) {\n        (void)band;')
 code=code.replace('malloc(', 'patch_malloc(').replace('calloc(', 'patch_calloc(')
 code=code.replace('Level *fine = &levels[0];','Level *fine = &levels[0], *coarsest = nullptr;')
 code=code.replace('Level *coarsest = &levels[count - 1];','coarsest = &levels[count - 1];')
 if wide:
  for var in ['rgba','s','t']:code=re.sub(r'\buint8_t(\s*\*'+var+r'\b)',r'uint16_t\1',code)
  code=code.replace('s[3] == 255','s[3] == 65535')
  code=code.replace('CH + c] = s[c];','CH + c] = s[c] / 257.0f;')
  code=code.replace('(uint8_t)lrintf(alpha)','(uint16_t)lrintf(alpha * 257.0f)')
  code=code.replace('(uint8_t)lrintf(v[c] < 0 ? 0 : v[c] > t[3] ? t[3] : v[c])','(uint16_t)lrintf((v[c] < 0 ? 0 : v[c] > t[3] / 257.0f ? t[3] / 257.0f : v[c]) * 257.0f)')
 headers='#include "WideKernels.h"\n' if wide else 'extern "C" {\n#include "PatchPixels.h"\n#include "HealPixels.h"\n}\n'
 headers+='#include "PixelParallel.h"\n#include <cmath>\n#include <cstdlib>\n#include <cstring>\n#include <cfloat>\n'
 allocation='struct PatchAllocation { void *p; template<class T> operator T *() const { return static_cast<T *>(p); } };\nstatic PatchAllocation patch_malloc(size_t n) { return {std::malloc(n)}; }\nstatic PatchAllocation patch_calloc(size_t n,size_t s) { return {std::calloc(n,s)}; }\n'
 banner='// Generated by windows/scripts/generate-patch-pixels.py from PatchPixels.c\n// Source SHA256: '+hashlib.sha256(original.encode()).hexdigest()+'\n'
 output=banner+headers+('namespace comp::wide {\n' if wide else '')+allocation+code+('\n}\n' if wide else '')
 (root/'windows/src'/('WidePatchPixels.cpp' if wide else 'PatchPixelsWindows.cpp')).write_text(output,encoding='utf-8',newline='\n')
